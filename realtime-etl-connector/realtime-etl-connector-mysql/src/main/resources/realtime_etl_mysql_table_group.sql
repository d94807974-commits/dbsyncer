CREATE TABLE `realtime_etl_table_group` (
  `ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Unique ID',
  `CREATE_TIME` bigint NOT NULL COMMENT 'Created at',
  `UPDATE_TIME` bigint NOT NULL COMMENT 'Updated at',
  `TASK_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Task ID',
  `SORT_INDEX` int NOT NULL DEFAULT 0 COMMENT 'Sort Number',
  `SOURCE_CONNECTOR_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Source Pool Connector ID',
  `TARGET_CONNECTOR_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Target library connector ID',
  `SOURCE_DATABASE` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Source database',
  `TARGET_DATABASE` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Target database',
  `SOURCE_SCHEMA` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Source',
  `TARGET_SCHEMA` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Target schema',
  `SOURCE_TABLE` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Source table',
  `TARGET_TABLE` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Target table',
  `SOURCE_TOTAL` bigint NOT NULL DEFAULT 0 COMMENT 'Total source table',
  `TARGET_TOTAL` bigint NOT NULL DEFAULT 0 COMMENT 'Total Regulatory Target Table',
  `JSON` mediumtext CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Configuration',
  PRIMARY KEY (`ID`) USING BTREE,
  KEY `IDX_TASK_ID` (`TASK_ID`, `SORT_INDEX`) USING BTREE,
  KEY `IDX_TG_MAPPING` (`TASK_ID`, `SOURCE_CONNECTOR_ID`, `TARGET_CONNECTOR_ID`, `SOURCE_DATABASE`, `TARGET_DATABASE`, `SOURCE_SCHEMA`, `TARGET_SCHEMA`, `SORT_INDEX`) USING BTREE,
  KEY `IDX_SOURCE_CONN_ID` (`SOURCE_CONNECTOR_ID`) USING BTREE,
  KEY `IDX_TARGET_CONN_ID` (`TARGET_CONNECTOR_ID`) USING BTREE
) ENGINE = InnoDB CHARACTER SET = utf8mb4 COLLATE = utf8mb4_bin COMMENT = 'Map Relationship Configuration Table' ROW_FORMAT = Dynamic;
