CREATE TABLE `realtime_etl_role_permission` (
  `ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Unique ID',
  `CREATE_TIME` bigint NOT NULL COMMENT 'Created at',
  `UPDATE_TIME` bigint NOT NULL COMMENT 'Updated at',
  `ROLE_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Role 42',
  `PERMISSION_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Permission ID',
  PRIMARY KEY (`ID`) USING BTREE,
  UNIQUE KEY `UK_ROLE_PERM` (`ROLE_ID`, `PERMISSION_ID`) USING BTREE,
  KEY `IDX_RP_PERM` (`PERMISSION_ID`) USING BTREE
) ENGINE = InnoDB CHARACTER SET = utf8mb4 COLLATE = utf8mb4_bin COMMENT = 'Role Compensation Table' ROW_FORMAT = Dynamic;
