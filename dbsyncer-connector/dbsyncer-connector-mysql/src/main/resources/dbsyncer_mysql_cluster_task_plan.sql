CREATE TABLE `dbsyncer_cluster_task_plan` (
  `ID`              bigint NOT NULL AUTO_INCREMENT COMMENT 'AutoAddition Primary Key',
  `TASK_ID`         varchar(64)  CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Task ID',
  `TABLE_GROUP_ID`  varchar(64)  CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Map ID',
  `NODE_ID`         varchar(64)  CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT 'Executive Node, {p}: {httpPort}',
  `START_CURSOR`    varchar(512) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT '' COMMENT 'Part Start Cursor',
  `END_CURSOR`      varchar(512) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT '' COMMENT 'Speculation End Curve',
  `LAST_CURSOR`     varchar(512) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT '' COMMENT 'Final Partition Curse',
  `SUCCESS`         bigint NOT NULL DEFAULT 0 COMMENT 'Successes',
  `FAIL`            bigint NOT NULL DEFAULT 0 COMMENT 'Failures',
  `DIFF`            bigint NOT NULL DEFAULT 0 COMMENT 'Diffs',
  `FIXED`           bigint NOT NULL DEFAULT 0 COMMENT 'Revised',
  `CONTENT`         JSON, sample of split error/discrepancies of mediamblob Null COMMENT, merged with TASK DETAIL',
  `STATUS`          tinyint NOT NULL DEFAULT 0 COMMENT '0-not completed, 1- running, 2-completed',
  `LAST_PAGE`       tinyint NOT NULL DEFAULT 0 COMMENT 'Last page at the end: 0-No, 1-Yes',
  `CREATE_TIME`     bigint NOT NULL COMMENT 'Created at',
  `UPDATE_TIME`     bigint NOT NULL COMMENT 'Change time (run centre jump/timeout determination)',
  PRIMARY KEY (`ID`),
  KEY `IDX_TASK_TABLE` (`TASK_ID`, `TABLE_GROUP_ID`, `STATUS`),
  KEY `IDX_NODE_STATUS` (`NODE_ID`, `STATUS`),
  KEY `IDX_TABLE_STATUS` (`TABLE_GROUP_ID`, `STATUS`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='Job Break Schedule';
